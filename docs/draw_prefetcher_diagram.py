def setup(ax,title):
 ax.set_xlim(0,100);ax.set_ylim(0,100);ax.axis('off');ax.add_patch(Rectangle((.5,.5),99,99,fill=False,edgecolor='#a6b5c0',lw=1));ax.text(3,96,title,fontsize=14,fontweight='bold',color=C,va='top')
def box(ax,x,y,w,h,t,seq=False,fs=9):
 ax.add_patch(Rectangle((x,y),w,h,facecolor=S if seq else 'white',edgecolor=C if seq else G,lw=1.2));ax.text(x+w/2,y+h/2,t,ha='center',va='center',fontsize=fs)
 if seq: ax.add_patch(Polygon([[x+2,y],[x+3.3,y+1.8],[x+4.6,y]],closed=False,fill=False,edgecolor=C,lw=1))
def mux(ax,x,y,w,h,t):
 ax.add_patch(Polygon([(x,y),(x+w,y+2),(x+w,y+h-2),(x,y+h)],closed=True,facecolor='white',edgecolor=G,lw=1.2));ax.text(x+w/2,y+h/2,t,ha='center',va='center',fontsize=8)
def arr(ax,p,q,label='',via=None):
 pts=[p]+(via or [])+[q]
 for a,b in zip(pts[:-2],pts[1:-1]): ax.plot([a[0],b[0]],[a[1],b[1]],color=G,lw=1)
 ax.annotate('',xy=pts[-1],xytext=pts[-2],arrowprops=dict(arrowstyle='->',color=G,lw=1))
 if label:
  a,b=pts[0],pts[1];ax.text((a[0]+b[0])/2,(a[1]+b[1])/2+1.7,label,fontsize=7.5,ha='center',color=G)
def txt(ax,x,y,t,fs=8):ax.text(x,y,t,fontsize=fs,ha='left',va='center',color=G)
